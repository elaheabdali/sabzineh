/**
 * Regenerates apps/web/src/ui-safelist.ts.
 *
 * Why: Tailwind v4 in this Turbopack setup only scans apps/web, so
 * utilities used ONLY in packages/ui are never emitted (verified:
 * `animate-spin`, `bg-red-700`, `border-dashed` were missing from the
 * production CSS). The safelist file lives in apps/web/src, so its
 * string literals ARE scanned and the utilities get emitted.
 *
 * Run after adding a utility that only packages/ui uses:
 *   node scripts/sync-ui-safelist.mjs
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (/\.(ts|tsx)$/.test(entry)) out.push(path);
  }
  return out;
}

// Class-like tokens: letters, digits, -, /, ., :, [, ], %, _ — inside quotes.
const TOKEN = /["'`]((?:[A-Za-z0-9\-_./:\[\]%]+)(?:\s+(?:[A-Za-z0-9\-_./:\[\]%]+))*)["'`]/g;

function tokensIn(files) {
  const found = new Set();
  for (const file of files) {
    const text = readFileSync(file, "utf8");
    for (const match of text.matchAll(TOKEN)) {
      for (const token of match[1].split(/\s+/)) {
        if (/^[a-z]/i.test(token) && token.length > 1) found.add(token);
      }
    }
  }
  return found;
}

// Bare single words are almost never utilities (they come from labels
// and variant names); keep only hyphenated/variant tokens plus a
// small allowlist of bare utilities.
const BARE_UTILITIES = new Set([
  "truncate", "shadow", "flex", "grid", "block", "hidden", "relative",
  "absolute", "fixed", "sticky", "underline", "italic", "rounded",
]);
const DENYLIST = new Set(["tailwind-merge", "clsx"]);
const looksLikeUtility = (t) =>
  !DENYLIST.has(t) &&
  /[-:/\[]/.test(t) || BARE_UTILITIES.has(t);

const uiTokens = tokensIn(walk(join(root, "packages/ui/src")));
// The safelist file itself must not be scanned as web usage, or it
// would cancel out every entry it lists.
const webFiles = walk(join(root, "apps/web/src")).filter((f) => !f.endsWith("ui-safelist.ts"));
const webTokens = tokensIn(webFiles);
const uiOnly = [...uiTokens]
  .filter((t) => !webTokens.has(t) && looksLikeUtility(t))
  .sort();

const out = `/**
 * Tailwind safelist for utilities used ONLY in @sabzineh/ui.
 *
 * Generated by scripts/sync-ui-safelist.mjs — do not hand-edit.
 * Tailwind v4 (Turbopack) scans apps/web only, so without this file
 * these utilities are missing from the production CSS. Re-run the
 * script after adding a ui-only utility.
 */
export const UI_SAFELIST: string[] = ${JSON.stringify(uiOnly, null, 2)};
`;
writeFileSync(join(root, "apps/web/src/ui-safelist.ts"), out, "utf8");
console.log(`ui-only utilities: ${uiOnly.length}`);
console.log(uiOnly.join(" "));
